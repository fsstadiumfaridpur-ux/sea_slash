const fields: (keyof MonthlyExpenseItem)[] = ['id', 'month', 'date', 'category', 'title', 'amount', 'paymentMode', 'vendor', 'notes', 'isRecurring'];
const fingerprints = new Set(retiredDemoExpenses.map(record => JSON.stringify(fields.map(field => record[field]))));

export function removeDemoExpenses(records: MonthlyExpenseItem[]): MonthlyExpenseItem[] {
  return records.filter(record => Object.keys(record).length !== fields.length || !fingerprints.has(JSON.stringify(fields.map(field => record[field]))));
}
